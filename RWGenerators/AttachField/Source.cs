using Microsoft.CodeAnalysis;
using System.Text;

namespace RWGenerators.AttachField;

internal static class Source
{
    public static string Generate(AttachedFieldInfo info)
    {
        if (info.FieldType == "bool" && info.Impl == 1)
            return GenerateHashSet(info);
        else if (info.IsValueType || info.DefaultValueString != null)
            return GenerateWithDefault(info);
        else
            return GenerateNormal(info);
    }

    public static string GenerateNormal(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string containerType = info.Impl switch
        {
            0 => "WeakTable",
            1 => "Dictionary",
            _ => throw new ArgumentException("Unknown AttachFieldImpl"),
        };

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;
using RWGenerators.Collections;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly {containerType}<{info.AttachToType}, {info.FieldType}> {containerName} = new({(info.Impl == 1 ? "ReferenceEqualityComparer.Instance": "")});

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => {containerName}.GetValue(attachedTo, () => {info.DefaultValueString ?? "new()"});
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set => {containerName}.SetValue(attachedTo, value);
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateWithDefault(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string defaultValueString = info.DefaultValueString ?? "default";
        string containerType = info.Impl switch
        {
            0 => "WeakTable",
            1 => "Dictionary",
            _ => throw new ArgumentException("Unknown AttachFieldImpl"),
        };

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;
using RWGenerators.Collections;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly {containerType}<{info.AttachToType}, {info.FieldType}> {containerName} = new({(info.Impl == 1 ? "ReferenceEqualityComparer.Instance" : "")});

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get
            {{
                if ({containerName}.TryGetValue(attachedTo, out {info.FieldType} value))
                    return value;
                else
                    return {defaultValueString};
            }}
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set
            {{
                if (value == {defaultValueString})
                    {containerName}.Remove(attachedTo);
                else
                    {containerName}.SetValue(attachedTo, value);
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateHashSet(AttachedFieldInfo info)
    {
        bool defaultTrue = info.DefaultValueString == "true";
        string containerName = $"s_{info.PropertyName}{(defaultTrue ? "False" : "True")}Fields";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;
using RWGenerators.Collections;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly HashSet<{info.AttachToType}> {containerName} = new(ReferenceEqualityComparer.Instance);

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => {(defaultTrue ? "!" : "")}{containerName}.Contains(attachedTo);
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set
            {{
                if ({(defaultTrue ? "!" : "")}value)
                    {containerName}.Add(attachedTo);
                else
                    {containerName}.Remove(attachedTo);
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateOptional(AttachedOptionalFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string lowerPropertyName = info.PropertyName.FirstCharToLower();
        string containerType = info.Impl switch
        {
            0 => "WeakTable",
            1 => "Dictionary",
            _ => throw new ArgumentException("Unknown AttachFieldImpl"),
        };

        StringBuilder extraMethods = new();
        if (info.AddGetOrCreateValue)
        {
            extraMethods.Append($@"
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public {info.FieldType} GetOrCreate{info.PropertyName}() => {containerName}.GetValue(attachedTo, () => new());
");
        }
        if (info.AddGetOrAddValue)
        {
            extraMethods.Append($@"
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public {info.FieldType} GetOrAdd{info.PropertyName}(Func<{info.FieldType}> valueFactory) => {containerName}.GetValue(attachedTo, valueFactory);
");
        }

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;
using RWGenerators.Collections;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly {containerType}<{info.AttachToType}, {info.FieldType}> {containerName} = new({(info.Impl == 1 ? "ReferenceEqualityComparer.Instance" : "")});

    extension ({info.AttachToType} attachedTo)
    {{
        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public bool TryGet{info.PropertyName}(out {info.FieldType} {lowerPropertyName}) => {containerName}.TryGetValue(attachedTo, out {lowerPropertyName});

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Set{info.PropertyName}({info.FieldType} {lowerPropertyName}) => {containerName}.SetValue(attachedTo, {lowerPropertyName});

        [MethodImpl(MethodImplOptions.AggressiveInlining)]
        public void Remove{info.PropertyName}() => {containerName}.Remove(attachedTo);
        {extraMethods}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }
}
