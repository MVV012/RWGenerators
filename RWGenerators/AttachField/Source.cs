using Microsoft.CodeAnalysis;

namespace RWGenerators.AttachField;

internal static class Source
{
    public static string Generate(AttachedFieldInfo info)
    {
        int impl = info.Impl;
        if (impl == 0) // Default
        {
            impl = info.FieldType == "bool"
                ? 1     // TODO: add optimized variant for bool
                : 1;    // CWT
        }

        return impl switch
        {
            1 => GenerateCWT(info),
            2 => GenerateStrongRefDict(info),
            _ => throw new ArgumentException("Unknown AttachFieldImpl"),
        };
    }

    public static string GenerateCWT(AttachedFieldInfo info)
    {
        return info.IsValueType ? GenerateCWTValueType(info) : GenerateCWTReferenceType(info);
    }

    public static string GenerateCWTReferenceType(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static ConditionalWeakTable<{info.AttachToType}, {info.FieldType}> {containerName} = new();

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            get => {containerName}.GetValue(attachedTo, (_) => {info.DefaultValueString ?? "new()"});
            set
            {{
                if ({containerName}.TryGetValue(attachedTo, out _))
                {{
                    {containerName}.Remove(attachedTo);
                }}
                {containerName}.Add(attachedTo, value);
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName} = new();
    }}
}}";
    }

    public static string GenerateCWTValueType(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string valueHolderClass = $"{info.PropertyName}ValueHolder";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private class {valueHolderClass}
    {{
        public {info.FieldType} Value = {info.DefaultValueString ?? "default"};
    }}
    private static ConditionalWeakTable<{info.AttachToType}, {valueHolderClass}> {containerName} = new();

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            get => {containerName}.GetValue(attachedTo, (_) => new()).Value;
            set => {containerName}.GetValue(attachedTo, (_) => new()).Value = value;
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName} = new();
    }}
}}";
    }

    public static string GenerateStrongRefDict(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";

        return $@"// <auto-generated/>
using System;
using System.Collections.Generic;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly Dictionary<{info.AttachToType}, {info.FieldType}> {containerName} = new();

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            get
            {{
                if (!{containerName}.TryGetValue(attachedTo, out {info.FieldType} value))
                {{
                    value = {info.DefaultValueString ?? "new()"};
                    {containerName}[attachedTo] = value;
                }}
                return value;
            }}
            set => {containerName}[attachedTo] = value;
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }
}
