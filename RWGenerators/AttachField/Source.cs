using Microsoft.CodeAnalysis;

namespace RWGenerators.AttachField;

internal static class Source
{
    public static string Generate(AttachedFieldInfo info) => info.Impl switch
    {
        0 => GenerateWeakTable(info),
        1 => GenerateStrongRefDict(info),
        _ => throw new ArgumentException("Unknown AttachFieldImpl"),
    };

    public static string GenerateWeakTable(AttachedFieldInfo info)
    {
        if (info.IsValueType || info.DefaultValueString != null)
            return GenerateWeakTableWithDefault(info);
        else
            return GenerateWeakTableNormal(info);
    }

    public static string GenerateWeakTableNormal(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly RWGenerators.Collections.WeakTable<{info.AttachToType}, {info.FieldType}> {containerName} = new();

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => {containerName}.GetValue(attachedTo, () => {info.DefaultValueString ?? "new()"});
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set => {containerName}.SetValue(attachedTo, value);
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateWeakTableWithDefault(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string defaultValueString = info.DefaultValueString ?? "default";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly RWGenerators.Collections.WeakTable<{info.AttachToType}, {info.FieldType}> {containerName} = new();

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get
            {{
                if ({containerName}.TryGetValue(attachedTo, out {info.FieldType} value))
                    return value;
                else
                    return {defaultValueString};
            }}
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set
            {{
                if (value == {defaultValueString})
                    {containerName}.Remove(attachedTo);
                else
                    {containerName}.SetValue(attachedTo, value);
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateStrongRefDict(AttachedFieldInfo info)
    {
        if (info.FieldType == "bool")
            return GenerateHashSet(info);
        if (info.IsValueType || info.DefaultValueString != null)
            return GenerateStrongRefDictWithDefault(info);
        else
            return GenerateStrongRefDictNormal(info);
    }

    public static string GenerateStrongRefDictNormal(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly Dictionary<{info.AttachToType}, {info.FieldType}> {containerName} = new(RWGenerators.Collections.ReferenceEqualityComparer.Instance);

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get
            {{
                if (!{containerName}.TryGetValue(attachedTo, out {info.FieldType} value))
                {{
                    value = {info.DefaultValueString ?? "new()"};
                    {containerName}[attachedTo] = value;
                }}
                return value;
            }}
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set => {containerName}[attachedTo] = value;
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateStrongRefDictWithDefault(AttachedFieldInfo info)
    {
        string containerName = $"s_{info.PropertyName}Fields";
        string defaultValueString = info.DefaultValueString ?? "default";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly Dictionary<{info.AttachToType}, {info.FieldType}> {containerName} = new(RWGenerators.Collections.ReferenceEqualityComparer.Instance);

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get
            {{
                if ({containerName}.TryGetValue(attachedTo, out {info.FieldType} value))
                    return value;
                else
                    return {defaultValueString};
            }}
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set
            {{
                if (value == {defaultValueString})
                    {containerName}.Remove(attachedTo);
                else
                    {containerName}[attachedTo] = value;
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }

    public static string GenerateHashSet(AttachedFieldInfo info)
    {
        bool defaultTrue = info.DefaultValueString == "true";
        string containerName = $"s_{info.PropertyName}{(defaultTrue ? "False" : "True")}Fields";

        return $@"// <auto-generated/>
using System;
using System.Runtime.CompilerServices;
using System.Collections.Generic;

namespace {info.ContainingClass.Namespace};

{info.ContainingClass.Modifiers} class {info.ContainingClass.Name}
{{
    private static readonly HashSet<{info.AttachToType}> {containerName} = new(RWGenerators.Collections.ReferenceEqualityComparer.Instance);

    extension ({info.AttachToType} attachedTo)
    {{
        public {info.FieldType} {info.PropertyName}
        {{
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            get => {(defaultTrue ? "!" : "")}{containerName}.Contains(attachedTo);
            [MethodImpl(MethodImplOptions.AggressiveInlining)]
            set
            {{
                if ({(defaultTrue ? "!" : "")}value)
                    {containerName}.Add(attachedTo);
                else
                    {containerName}.Remove(attachedTo);
            }}
        }}
        public static void ClearAll{info.PropertyName}Fields() => {containerName}.Clear();
    }}
}}";
    }
}
