using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;
using System.Text;

namespace RWGenerators;

[Generator]
public class ConfigAccessorsGenerator : IIncrementalGenerator
{
    internal record class GeneratedClassInfo(
        string Name,
        string Namespace,
        string SourceFullName,
        EquatableArray<(string Name, string Type)> Configurables)
    {}

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(AddAttribute);

        IncrementalValuesProvider<GeneratedClassInfo> generatedClasses = context.SyntaxProvider
            .ForAttributeWithMetadataName($"RWGenerators.GenerateConfigAccessorsAttribute",
                (_, _) => true,
                GetGeneratedClassInfo)
            .Where(x => x != null)!;

        context.RegisterSourceOutput(generatedClasses, GenerateSource);
    }

    private void AddAttribute(IncrementalGeneratorPostInitializationContext ctx)
    {
        ctx.AddEmbeddedAttributeDefinition();
        ctx.AddEmbeddedSource("GenerateConfigAccessorsAttribute.g.cs");
    }

    private GeneratedClassInfo? GetGeneratedClassInfo(GeneratorAttributeSyntaxContext ctx, CancellationToken cancellationToken)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol classSymbol
            || ctx.TargetNode is not ClassDeclarationSyntax classSyntax)
        {
            return null;
        }

        AttributeData attributeData = ctx.Attributes[0];
        if (attributeData.ConstructorArguments.First().Value is not string attributeArgument)
            return null;

        (string generatedName, string? generatedNamespace) = Utils.SplitNameAndNamespace(attributeArgument);
        generatedNamespace ??= classSyntax.GetDeclarationNamespace();

        ImmutableArray<ISymbol> members = classSymbol.GetMembers();
        var builder = ImmutableArray.CreateBuilder<(string Name, string Type)>(Math.Max(members.Length / 2, 8));

        foreach (ISymbol symbol in members)
        {
            if (symbol is IPropertySymbol { IsStatic: true, Type: INamedTypeSymbol { Name: "Configurable" } propertyType })
            {
                builder.Add((symbol.Name, propertyType.TypeArguments[0].FullyQualifiedName));
            }
            else if (symbol is IFieldSymbol { IsStatic: true, AssociatedSymbol: null, Type: INamedTypeSymbol { Name: "Configurable" } fieldType })
            {
                builder.Add((symbol.Name, fieldType.TypeArguments[0].FullyQualifiedName));
            }
        }

        return new GeneratedClassInfo(
            generatedName,
            generatedNamespace,
            classSymbol.FullyQualifiedName,
            new(builder.ToImmutable())
        );
    }

    private void GenerateSource(SourceProductionContext ctx, GeneratedClassInfo generatedClassInfo)
    {
        StringBuilder generatedProperties = new();
        foreach ((string Name, string Type) in generatedClassInfo.Configurables)
        {
            generatedProperties.Append($"    public static {Type} {Name} => {generatedClassInfo.SourceFullName}.{Name}.Value;");
            generatedProperties.AppendLine();
        }

        ctx.AddSource($"{generatedClassInfo.Name}.g.cs", $@"// <auto-generated/>
namespace {generatedClassInfo.Namespace};

public static partial class {generatedClassInfo.Name}
{{
{generatedProperties}
}}
");
    }
}
